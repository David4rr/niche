import AppKit
import Carbon.HIToolbox
import SwiftUI

@MainActor
@Observable
final class ClipboardHistory {
    enum Kind: Equatable { case text, link, color, image, files }

    struct Item: Identifiable {
        let id = UUID()
        let kind: Kind, text: String, image: NSImage?, imageData: Data?
        let imageType: NSPasteboard.PasteboardType?, files: [URL]
        let app: NSImage?, appName: String?, date = Date(), signature: Int
    }
    struct DragPreview {
        let title: String, subtitle: String, icon: NSImage?, symbol: String, count: Int
    }
    private(set) var items: [Item] = []
    private(set) var selectedIDs: [UUID] = []
    private(set) var dragPreview: DragPreview?
    var selection = 0
    private(set) var isKeyboard = false
    @ObservationIgnored var isDraggingOut = false
    var isOn: Bool { didSet { UserDefaults.standard.set(isOn, forKey: "clipboard"); if !isOn { items.removeAll(); selectedIDs.removeAll() } } }
    var limit: Int { didSet { UserDefaults.standard.set(limit, forKey: "clipboardLimit"); trimToLimit() } }
    var pastesOnPick: Bool { didSet { UserDefaults.standard.set(pastesOnPick, forKey: "clipboardPastes") } }
    var shortcutOn: Bool { didSet { UserDefaults.standard.set(shortcutOn, forKey: "clipboardShortcut"); registerHotKey() } }
    @ObservationIgnored var onCopied: ((Item) -> Void)?
    @ObservationIgnored var onHotKey: (() -> Void)?
    @ObservationIgnored private var lastChange = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var hotKey: EventHotKeyRef?
    @ObservationIgnored private static var shared: ClipboardHistory?
    static let maxLimit = 10
    private static let maxImageBytes = 4 << 20
    private static let skipped: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                               "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    init() {
        let d = UserDefaults.standard
        d.register(defaults: ["clipboard": true, "clipboardLimit": Self.maxLimit, "clipboardPastes": true, "clipboardShortcut": true])
        isOn = d.bool(forKey: "clipboard"); limit = min(max(d.integer(forKey: "clipboardLimit"), 3), Self.maxLimit)
        pastesOnPick = d.bool(forKey: "clipboardPastes"); shortcutOn = d.bool(forKey: "clipboardShortcut")
        Self.shared = self
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { _ in MainActor.assumeIsolated { ClipboardHistory.shared?.poll() } }
        var spec = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
        InstallEventHandler(GetApplicationEventTarget(), { _, _, _ in Task { @MainActor in ClipboardHistory.shared?.onHotKey?() }; return noErr }, 1, &spec, nil, nil)
        registerHotKey()
    }
    private func registerHotKey() {
        if let hotKey { UnregisterEventHotKey(hotKey) }; hotKey = nil
        guard shortcutOn else { return }
        RegisterEventHotKey(UInt32(kVK_ANSI_V), UInt32(cmdKey | controlKey), EventHotKeyID(signature: OSType(0x4E434C50), id: 1), GetApplicationEventTarget(), 0, &hotKey)
    }

    private func poll() {
        let board = NSPasteboard.general
        guard board.changeCount != lastChange else { return }
        lastChange = board.changeCount
        guard isOn, let types = board.types, !types.contains(where: { Self.skipped.contains($0.rawValue) }),
              let item = read(board) else { return }
        insert(item); onCopied?(item)
    }

    private func read(_ board: NSPasteboard) -> Item? {
        let front = NSWorkspace.shared.frontmostApplication
        let app = front?.icon, appName = front?.localizedName
        if let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let icon = NSWorkspace.shared.icon(forFile: urls[0].path)
            return Item(kind: .files, text: urls.map(\.lastPathComponent).joined(separator: ", "),
                        image: icon, imageData: nil, imageType: nil, files: urls, app: app, appName: appName, signature: urls.hashValue)
        }
        if let string = board.string(forType: .string) {
            let t = string.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !t.isEmpty else { return nil }
            let kind: Kind = (!t.contains(where: \.isWhitespace) && URL(string: t)?.scheme?.hasPrefix("http") == true && URL(string: t)?.host != nil) ? .link : (Self.color(from: t) != nil ? .color : .text)
            return Item(kind: kind, text: String(string.prefix(4096)), image: nil, imageData: nil, imageType: nil, files: [], app: app, appName: appName, signature: t.hashValue)
        }
        for type in [NSPasteboard.PasteboardType.png, .tiff] {
            guard let data = board.data(forType: type), data.count <= Self.maxImageBytes, let image = NSImage(data: data) else { continue }
            return Item(kind: .image, text: "Image \(Int(image.size.width)) × \(Int(image.size.height))", image: Self.thumbnail(image, side: 96),
                        imageData: data, imageType: type, files: [], app: app, appName: appName, signature: data.hashValue)
        }
        return nil
    }
    static func inspect(_ board: NSPasteboard) -> DragPreview {
        if let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let icon = NSWorkspace.shared.icon(forFile: urls[0].path)
            let title = urls.count == 1 ? urls[0].lastPathComponent : "\(urls.count) Files"
            let sub = urls.count == 1 ? "Drop to add file to Clipboard" : "Drop \(urls.count) files to Clipboard"
            return DragPreview(title: title, subtitle: sub, icon: icon, symbol: "doc.on.doc.fill", count: urls.count)
        }
        if let raw = board.string(forType: .string) {
            let t = String(raw.prefix(120)).trimmingCharacters(in: .whitespacesAndNewlines)
            if !t.isEmpty {
                let line = t.split(whereSeparator: \.isNewline).first.map(String.init) ?? t
                return DragPreview(title: line, subtitle: "Drop text to Clipboard", icon: nil, symbol: "doc.on.clipboard.fill", count: 1)
            }
        }
        if board.availableType(from: [.png, .tiff]) != nil {
            return DragPreview(title: "Image", subtitle: "Drop image to Clipboard", icon: nil, symbol: "photo.on.rectangle.angled", count: 1)
        }
        return DragPreview(title: "Drop to copy", subtitle: "Add to Clipboard", icon: nil, symbol: "tray.and.arrow.down.fill", count: 1)
    }
    func setDragPreview(_ board: NSPasteboard?) {
        dragPreview = board.map(Self.inspect)
    }
    func take(_ board: NSPasteboard) -> Bool {
        guard isOn else { return false }
        if let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], urls.count > 1 {
            let front = NSWorkspace.shared.frontmostApplication
            let app = front?.icon, appName = front?.localizedName
            let gen = NSPasteboard.general; gen.clearContents(); gen.writeObjects(urls as [NSURL]); lastChange = gen.changeCount
            var lastItem: Item?
            for url in urls.reversed() {
                let icon = NSWorkspace.shared.icon(forFile: url.path)
                let item = Item(kind: .files, text: url.lastPathComponent, image: icon, imageData: nil, imageType: nil, files: [url], app: app, appName: appName, signature: [url].hashValue)
                insert(item); lastItem = item
            }
            if let lastItem { onCopied?(lastItem) }
            return true
        }
        guard let item = read(board) else { return false }
        writeGeneral(item); insert(item); onCopied?(item); return true
    }
    private func writeGeneral(_ item: Item) {
        let board = NSPasteboard.general; board.clearContents()
        switch item.kind {
        case .files: board.writeObjects(item.files as [NSURL])
        case .image: if let data = item.imageData, let type = item.imageType { board.setData(data, forType: type) }
        case .text, .link, .color: board.setString(item.text, forType: .string)
        }
        lastChange = board.changeCount
    }
    private func insert(_ item: Item) {
        withAnimation(.spring(response: 0.36, dampingFraction: 0.86)) {
            items.removeAll { $0.signature == item.signature }; items.insert(item, at: 0); trimToLimit()
        }
    }
    private func trimToLimit() { if items.count > limit { items.removeSubrange(limit...) } }
    func toggleSelect(_ item: Item) {
        if let idx = selectedIDs.firstIndex(of: item.id) { selectedIDs.remove(at: idx) } else { selectedIDs.append(item.id) }
    }
    func selectAll() { selectedIDs = items.map(\.id) }
    func clearSelection() { selectedIDs.removeAll() }
    func copySelected() -> Item? {
        let chosen = selectedIDs.compactMap { id in items.first { $0.id == id } }
        guard let first = chosen.first else { return nil }
        if chosen.count == 1 { copy(first); selectedIDs.removeAll(); return first }
        let board = NSPasteboard.general; board.clearContents()
        let urls = chosen.flatMap(\.files)
        if !urls.isEmpty && chosen.allSatisfy({ $0.kind == .files }) {
            board.writeObjects(urls as [NSURL])
        } else {
            board.setString(chosen.map(\.text).joined(separator: "\n"), forType: .string)
            if !urls.isEmpty { board.writeObjects(urls as [NSURL]) }
        }
        lastChange = board.changeCount
        selectedIDs.removeAll()
        return first
    }
    func itemProvider(for item: Item) -> NSItemProvider {
        isDraggingOut = true
        switch item.kind {
        case .files: if let url = item.files.first, let p = NSItemProvider(contentsOf: url) { return p }
        case .image:
            if let data = item.imageData, let img = NSImage(data: data) { return NSItemProvider(object: img) }
            if let img = item.image { return NSItemProvider(object: img) }
        case .link: if let url = URL(string: item.text.trimmingCharacters(in: .whitespacesAndNewlines)) { return NSItemProvider(object: url as NSURL) }
        case .text, .color: break
        }
        return NSItemProvider(object: item.text as NSString)
    }
    func copy(_ item: Item) {
        writeGeneral(item)
        withAnimation(.spring(response: 0.36, dampingFraction: 0.86)) { items.removeAll { $0.id == item.id }; items.insert(item, at: 0) }
    }
    func remove(_ item: Item) {
        withAnimation(.spring(response: 0.36, dampingFraction: 0.86)) {
            items.removeAll { $0.id == item.id }; selectedIDs.removeAll { $0 == item.id }; selection = min(selection, max(items.count - 1, 0))
        }
    }
    func clear() { withAnimation(.spring(response: 0.36, dampingFraction: 0.86)) { items.removeAll(); selectedIDs.removeAll(); selection = 0 } }
    func setKeyboard(_ on: Bool) { isKeyboard = on; selection = 0; if !on { selectedIDs.removeAll() } }
    static func domain(_ text: String) -> String {
        guard let host = URL(string: text.trimmingCharacters(in: .whitespacesAndNewlines))?.host() else { return text }
        return host.hasPrefix("www.") ? String(host.dropFirst(4)) : host
    }
    static func thumbnail(_ image: NSImage, side: CGFloat) -> NSImage {
        let w = image.size.width, h = image.size.height
        guard w > 0, h > 0 else { return image }
        let scale = min(side / max(w, h), 1)
        let size = NSSize(width: max(1, round(w * scale)), height: max(1, round(h * scale)))
        return NSImage(size: size, flipped: false) { rect in
            NSGraphicsContext.current?.imageInterpolation = .medium
            image.draw(in: rect)
            return true
        }
    }
    static func color(from text: String) -> Color? {
        guard text.count == 7 || text.count == 4, text.hasPrefix("#") else { return nil }
        var hex = String(text.dropFirst())
        if hex.count == 3 { hex = hex.map { "\($0)\($0)" }.joined() }
        guard let value = UInt32(hex, radix: 16) else { return nil }
        return Color(red: Double((value >> 16) & 0xff) / 255, green: Double((value >> 8) & 0xff) / 255, blue: Double(value & 0xff) / 255)
    }
}
final class DropCatcherView: NSView {
    private let lab: LabState
    init(lab: LabState) { self.lab = lab; super.init(frame: .zero); registerForDraggedTypes([.fileURL, .URL, .string, .png, .tiff]) }
    required init?(coder: NSCoder) { fatalError("use init(lab:)") }
    override func wantsPeriodicDraggingUpdates() -> Bool { false }
    override func draggingEntered(_ sender: NSDraggingInfo) -> NSDragOperation {
        guard lab.canDrop, !lab.clipboard.isDraggingOut else { return [] }
        lab.clipboard.setDragPreview(sender.draggingPasteboard)
        lab.setDropTarget(true)
        return .copy
    }
    override func draggingUpdated(_ sender: NSDraggingInfo) -> NSDragOperation {
        lab.canDrop && !lab.clipboard.isDraggingOut ? .copy : []
    }
    override func draggingExited(_ sender: NSDraggingInfo?) {
        lab.setDropTarget(false)
        lab.clipboard.setDragPreview(nil)
    }
    override func performDragOperation(_ sender: NSDraggingInfo) -> Bool {
        lab.setDropTarget(false)
        lab.clipboard.setDragPreview(nil)
        return lab.clipboard.take(sender.draggingPasteboard)
    }
}
final class KeyCatcher: NSPanel {
    var onKey: ((NSEvent) -> Void)?
    init() {
        super.init(contentRect: NSRect(x: 0, y: 0, width: 1, height: 1), styleMask: [.borderless, .nonactivatingPanel], backing: .buffered, defer: true)
        alphaValue = 0; level = .statusBar; collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary]
    }
    override var canBecomeKey: Bool { true }
    override func keyDown(with event: NSEvent) { onKey?(event) }
}
